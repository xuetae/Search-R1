#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=env.sh
source "${SCRIPT_DIR}/env.sh"

if [[ -d /workspace/model_out ]]; then
  export OUTPUT_ROOT="${PLATFORM_OUTPUT_ROOT:-/workspace/model_out/search-r1/outputs}"
fi
EXPERIMENT_NAME="${EXPERIMENT_NAME:-llama7b-grpo-exact-gpu-paper-data}"
RUN_MODE="${RUN_MODE:-two_gpu_llama_instruct_exact_gpu_paper_data}"
case "${RUN_MODE}" in
  two_gpu_llama_instruct_exact_gpu_step10)
    TRAIN_BATCH_SIZE="${TRAIN_BATCH_SIZE:-32}"
    PPO_MINI_BATCH_SIZE="${PPO_MINI_BATCH_SIZE:-32}"
    PAPER_PROMPT_SAMPLES="${PAPER_PROMPT_SAMPLES:-171520}"
    DEFAULT_N_AGENT=3
    DEFAULT_MAX_TURNS=2
    DEFAULT_MAX_START_LENGTH=1792
    DEFAULT_MAX_PROMPT_LENGTH=3072
    DEFAULT_MAX_RESPONSE_LENGTH=256
    DEFAULT_MAX_OBS_LENGTH=384
    DEFAULT_MAX_NUM_SEQS=64
    DEFAULT_ROLLOUT_GPU_MEMORY_UTILIZATION=0.55
    DEFAULT_SAVE_FREQ=1600
    ;;
  *)
    TRAIN_BATCH_SIZE="${TRAIN_BATCH_SIZE:-128}"
    PPO_MINI_BATCH_SIZE="${PPO_MINI_BATCH_SIZE:-${TRAIN_BATCH_SIZE}}"
    PAPER_PROMPT_SAMPLES="${PAPER_PROMPT_SAMPLES:-514048}"
    DEFAULT_N_AGENT=5
    DEFAULT_MAX_TURNS=4
    DEFAULT_MAX_START_LENGTH=2048
    DEFAULT_MAX_PROMPT_LENGTH=3596
    DEFAULT_MAX_RESPONSE_LENGTH=500
    DEFAULT_MAX_OBS_LENGTH=500
    DEFAULT_MAX_NUM_SEQS=32
    DEFAULT_ROLLOUT_GPU_MEMORY_UTILIZATION=0.5
    DEFAULT_SAVE_FREQ=400
    ;;
esac
ACTUAL_UPDATES=$(((PAPER_PROMPT_SAMPLES + TRAIN_BATCH_SIZE - 1) / TRAIN_BATCH_SIZE))
TOTAL_TRAINING_STEPS="${TOTAL_TRAINING_STEPS:-$((ACTUAL_UPDATES + 1))}"
FINAL_UPDATE=$((TOTAL_TRAINING_STEPS - 1))
EVAL_BATCH_SIZE="${EVAL_BATCH_SIZE:-64}"
RETRIEVER_PYTHON="${RETRIEVER_PYTHON:-/workspace/filesdir/miniforge3/envs/retriever-gpu/bin/python}"
TRAIN_PYTHON_BIN="${TRAIN_PYTHON_BIN:-/usr/bin/python3}"
EVAL_LOG="${EVAL_LOG:-${OUTPUT_ROOT}/eval-${EXPERIMENT_NAME}-full.log}"

cd "${WORK_DIR}"
mkdir -p "${OUTPUT_ROOT}"

EXPERIMENT_NAME="${EXPERIMENT_NAME}" \
TRAIN_DATA_NUM=null \
VAL_DATA_NUM=512 \
TRAIN_BATCH_SIZE="${TRAIN_BATCH_SIZE}" \
VAL_BATCH_SIZE=64 \
PPO_MINI_BATCH_SIZE="${PPO_MINI_BATCH_SIZE}" \
PPO_MICRO_BATCH_SIZE="${PPO_MICRO_BATCH_SIZE:-8}" \
LOG_PROB_MICRO_BATCH_SIZE="${LOG_PROB_MICRO_BATCH_SIZE:-16}" \
N_AGENT="${N_AGENT:-${DEFAULT_N_AGENT}}" \
MAX_TURNS="${MAX_TURNS:-${DEFAULT_MAX_TURNS}}" \
MAX_START_LENGTH="${MAX_START_LENGTH:-${DEFAULT_MAX_START_LENGTH}}" \
MAX_PROMPT_LENGTH="${MAX_PROMPT_LENGTH:-${DEFAULT_MAX_PROMPT_LENGTH}}" \
MAX_RESPONSE_LENGTH="${MAX_RESPONSE_LENGTH:-${DEFAULT_MAX_RESPONSE_LENGTH}}" \
MAX_OBS_LENGTH="${MAX_OBS_LENGTH:-${DEFAULT_MAX_OBS_LENGTH}}" \
MAX_NUM_SEQS="${MAX_NUM_SEQS:-${DEFAULT_MAX_NUM_SEQS}}" \
MAX_NUM_BATCHED_TOKENS="${MAX_NUM_BATCHED_TOKENS:-4096}" \
ROLLOUT_GPU_MEMORY_UTILIZATION="${ROLLOUT_GPU_MEMORY_UTILIZATION:-${DEFAULT_ROLLOUT_GPU_MEMORY_UTILIZATION}}" \
RETRIEVER_TOPK=3 \
REWARD_SCORE_PRINT_PROB="${REWARD_SCORE_PRINT_PROB:-0}" \
PAPER_PROMPT_SAMPLES="${PAPER_PROMPT_SAMPLES}" \
TOTAL_TRAINING_STEPS="${TOTAL_TRAINING_STEPS}" \
VAL_BEFORE_TRAIN=false \
FINAL_VALIDATION=false \
FINAL_SAVE=true \
TEST_FREQ=-1 \
SAVE_FREQ="${SAVE_FREQ:-${DEFAULT_SAVE_FREQ}}" \
PYTHON_BIN="${RETRIEVER_PYTHON}" \
TRAIN_PYTHON_BIN="${TRAIN_PYTHON_BIN}" \
"${TRAIN_PYTHON_BIN}" "${SCRIPT_DIR}/training_task_entry.py" \
  --algo grpo \
  --run-mode "${RUN_MODE}" \
  --cuda-visible-devices 0,1 \
  --train-cuda-visible-devices 0,1 \
  --retriever-cuda-visible-devices 0,1

EVAL_MODEL="${OUTPUT_ROOT}/checkpoints/${EXPERIMENT_NAME}/actor/global_step_${FINAL_UPDATE}"
if [[ ! -d "${EVAL_MODEL}" ]]; then
  echo "Final checkpoint does not exist: ${EVAL_MODEL}" >&2
  exit 1
fi

CUDA_VISIBLE_DEVICES=0,1 \
RETRIEVER_DEVICE=cuda \
RETRIEVER_FAISS_GPU=1 \
EXPECTED_RETRIEVER_INDEX=flat \
RETRIEVER_TOPK=3 \
RETRIEVER_MAX_RETURN_TOKENS=0 \
INDEX_FILE="${WIKI18_DIR}/e5_Flat.index" \
CORPUS_FILE="${WIKI18_DIR}/wiki-18.jsonl" \
PYTHON_BIN="${RETRIEVER_PYTHON}" \
bash "${SCRIPT_DIR}/launch_retriever.sh" \
  > "${OUTPUT_ROOT}/retriever-${EXPERIMENT_NAME}-eval.log" 2>&1 &

RETRIEVER_PID=$!
cleanup() {
  kill "${RETRIEVER_PID}" 2>/dev/null || true
}
trap cleanup EXIT

for _ in $(seq 1 360); do
  if curl -fsS http://127.0.0.1:8000/docs >/dev/null; then
    break
  fi
  if ! kill -0 "${RETRIEVER_PID}" 2>/dev/null; then
    echo "Exact-GPU retriever failed; inspect ${OUTPUT_ROOT}/retriever-${EXPERIMENT_NAME}-eval.log" >&2
    exit 1
  fi
  sleep 5
done
curl -fsS http://127.0.0.1:8000/docs >/dev/null

CUDA_VISIBLE_DEVICES=0,1 \
TRAIN_PYTHON_BIN="${TRAIN_PYTHON_BIN}" \
EVAL_MODEL="${EVAL_MODEL}" \
EVAL_DATA_NUM=null \
EVAL_BATCH_SIZE="${EVAL_BATCH_SIZE}" \
MAX_TURNS="${EVAL_MAX_TURNS:-${MAX_TURNS:-${DEFAULT_MAX_TURNS}}}" \
EVAL_MAX_TURNS="${EVAL_MAX_TURNS:-${MAX_TURNS:-${DEFAULT_MAX_TURNS}}}" \
MAX_START_LENGTH="${EVAL_MAX_START_LENGTH:-${MAX_START_LENGTH:-${DEFAULT_MAX_START_LENGTH}}}" \
MAX_PROMPT_LENGTH="${EVAL_MAX_PROMPT_LENGTH:-${MAX_PROMPT_LENGTH:-${DEFAULT_MAX_PROMPT_LENGTH}}}" \
MAX_RESPONSE_LENGTH="${EVAL_MAX_RESPONSE_LENGTH:-${MAX_RESPONSE_LENGTH:-${DEFAULT_MAX_RESPONSE_LENGTH}}}" \
MAX_OBS_LENGTH="${EVAL_MAX_OBS_LENGTH:-${MAX_OBS_LENGTH:-${DEFAULT_MAX_OBS_LENGTH}}}" \
MAX_NUM_SEQS="${EVAL_MAX_NUM_SEQS:-${DEFAULT_MAX_NUM_SEQS}}" \
MAX_NUM_BATCHED_TOKENS="${EVAL_MAX_NUM_BATCHED_TOKENS:-4096}" \
ROLLOUT_GPU_MEMORY_UTILIZATION="${EVAL_GPU_MEMORY_UTILIZATION:-${DEFAULT_ROLLOUT_GPU_MEMORY_UTILIZATION}}" \
LOG_PROB_MICRO_BATCH_SIZE="${EVAL_LOG_PROB_MICRO_BATCH_SIZE:-16}" \
RETRIEVER_TOPK=3 \
N_GPUS_PER_NODE=2 \
NNODES=1 \
bash "${SCRIPT_DIR}/evaluate_7b_base.sh" \
  2>&1 | tee "${EVAL_LOG}"
